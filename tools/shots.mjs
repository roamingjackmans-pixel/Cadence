// Screenshots of a few scenes: node tools/shots.mjs <outDir> [url]
import { createRequire } from 'node:module';
const require = createRequire((process.env.PLAYWRIGHT_DIR || 'C:/dev/DungeonJoe') + '/package.json');
const { chromium } = require('playwright');
const out = process.argv[2] || '.';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1.5 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(process.argv[3] || 'http://127.0.0.1:8765/');
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.__cadence);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.screenshot({ path: `${out}/0-title.png` });
await page.evaluate(() => { const g = window.__cadence; g.newGame(); });
await sleep(1500);
await page.screenshot({ path: `${out}/1-start.png` });
await page.evaluate(() => { const w = window.__cadence.world; w.autoplay = true; w.p.x = 92 * 32; w.p.y = 42 * 32; });
await page.waitForFunction(() => { const w = window.__cadence.world; return w.cond.notes.filter((n) => !n.result && n.time - w.t < 1 && n.time - w.t > 0.5).length > 0; }, null, { timeout: 15000 });
await page.screenshot({ path: `${out}/2-fight.png` });
await page.evaluate(() => { const g = window.__cadence; g.world.spawn('b2'); const w = g.world; w.autoplay = true; w.p.x = 160 * 32; w.p.y = 34 * 32; window.dispatchEvent(new KeyboardEvent('keydown', { code: 'KeyD' })); });
await sleep(450);
await page.evaluate(() => window.dispatchEvent(new KeyboardEvent('keyup', { code: 'KeyD' })));
await page.waitForFunction(() => window.__cadence.world.attackers().length === 2, null, { timeout: 15000 }).catch(() => {});
await sleep(1200);
await page.screenshot({ path: `${out}/3-two-sided.png` });
await page.evaluate(() => { const g = window.__cadence; g.autoplay = true; g.world.p.x = 213 * 32; g.world.p.y = 34 * 32; g.world.startCut(); });
await sleep(1800);
await page.screenshot({ path: `${out}/4-walk-in.png` });
await sleep(4200);
await page.screenshot({ path: `${out}/5-intro.png` });
await sleep(5000);
await page.screenshot({ path: `${out}/6-duel.png` });
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
await browser.close();
